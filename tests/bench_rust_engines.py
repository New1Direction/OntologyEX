def correctness(status: str, detail: str) -> dict:
    return {"status": status, "detail": detail}


def not_run(reason: str) -> dict:
    return {"status": "NOT_RUN", "reason": reason}


def discovery(binary: Path | None, repo: Path, size: dict, runs: int, warmup: int) -> dict:
    commands = {"python": [sys.executable, str(SCRIPTS / "discover_repo.py"), "--repo", str(repo)],
                "rust": [str(binary), "--repo", str(repo)] if binary else None}
    engines, outputs = {}, {}
    for name, command in commands.items():
        if command is None:
            engines[name] = not_run("no ontologyex-discover binary")
            continue
        samples, seen = [], set()
        for i in range(warmup + runs):
            sample, data = run_once(command)
            seen.add(sha256(data))
            outputs.setdefault(name, data)
            if i >= warmup:
                samples.append(sample)
        if len(seen) > 1:
            outputs[name] = None  # not even the same as itself
        peak = peak_memory_kib(command)
        engines[name] = {"status": "MEASURED", "runs": runs, "warmup_runs": warmup,
                         "wall_seconds": summary([s["wall"] for s in samples]),
                         "cpu_seconds": summary([s["cpu"] for s in samples]),
                         "cores_used": round(statistics.median(s["cpu"] / s["wall"] for s in samples), 2),
                         "peak_rss_mib": round(peak / 1024, 1) if peak else None,
                         "files_per_cpu_second": round(size["files"] / statistics.median(s["cpu"] for s in samples)),
                         "output_sha256": sha256(outputs[name]) if outputs[name] is not None else None}
    if any(outputs.get(n, b"") is None for n in commands):
        check = correctness("DIFFERENT", "an engine gave different output on different runs of the same input")
    elif "rust" not in outputs:
        check = correctness("NOT_COMPARED", "Rust was not run")
    elif outputs["python"] == outputs["rust"]:
        check = correctness("SAME", f"byte-identical output in every run ({len(outputs['rust']):,} bytes, "
                                    f"sha256 {sha256(outputs['rust'])[:12]})")
    else:
        check = correctness("DIFFERENT", f"outputs differ: python sha256 {sha256(outputs['python'])[:12]}, "
                                         f"rust sha256 {sha256(outputs['rust'])[:12]}")
    return {"workload": "discovery", "title": "Repository discovery", "input": size,
            "method": "CLI to CLI, process start included, on a generated repository (synthetic)",
            "engines": engines, "correctness": check, "comparison": compare(engines, check, "discovery")}


def entity_context_workload(binary: Path | None, bundle: dict, runs: int, warmup: int) -> dict:
    ids = sorted(entity_context.entity_ids(bundle))
    view = native_view_bridge.NativeView(binary) if binary else None
    answer = {"python": lambda: [entity_context.context(bundle, i) for i in ids],
              "rust": (lambda: [view.execute(bundle, "context", i) for i in ids]) if view else None}
    engines, answers = {}, {}
    for name, fn in answer.items():
        if fn is None:
            engines[name] = not_run("no ontologyex-view binary")
            continue
        samples = []
        for i in range(warmup + runs):
            cpu0, child0, started = time.process_time(), children_cpu(), time.perf_counter()
            result = fn()
            wall = time.perf_counter() - started
            cpu = time.process_time() - cpu0 + children_cpu() - child0
            if i == 0:
                answers[name] = result
            elif result != answers[name]:
                answers[name] = None
            if i >= warmup:
                samples.append({"wall": wall, "cpu": cpu})
        engines[name] = {"status": "MEASURED", "runs": runs, "warmup_runs": warmup,
                         "wall_seconds": summary([s["wall"] for s in samples], 5),
                         "cpu_seconds": summary([s["cpu"] for s in samples], 5),
                         "cores_used": round(statistics.median(s["cpu"] / s["wall"] for s in samples), 2),
                         "peak_rss_mib": None,
                         "peak_rss_note": ("not measured: answers inside the calling process" if name == "python"
                                           else "not measured: a short process per answer"),
                         "answers_per_second": round(len(ids) / statistics.median(s["wall"] for s in samples))}
    if any(answers.get(n, []) is None for n in answer):
        check = correctness("DIFFERENT", "an engine gave different answers on different runs of the same input")
    elif "rust" not in answers:
        check = correctness("NOT_COMPARED", "Rust was not run")
    elif answers["python"] == answers["rust"]:
        check = correctness("SAME", f"the same answer for all {len(ids)} entities, in every run")
    else:
        wrong = [i for i, a, b in zip(ids, answers["python"], answers["rust"]) if a != b]
        check = correctness("DIFFERENT", f"{len(wrong)} of {len(ids)} entities differ, first {wrong[0]}")
    return {"workload": "entity_context", "title": "Entity context, every entity of the demo", "input": {"entities": len(ids)},
            "method": "as the control room computes it: Python in its own process, Rust one ontologyex-view "
                      "process per answer; the demo bundle (synthetic)",
            "engines": engines, "correctness": check, "comparison": compare(engines, check, "entity_context")}


def _client(port: int, body: bytes, start_at: float, stop_at: float, results) -> None:
    """One load-generating process: POST the same request until stop_at; count what was acknowledged."""
    time.sleep(max(0.0, start_at - time.time()))
    cpu0 = time.process_time()
    acked = failed = 0
    while time.time() < stop_at:
        request = urllib.request.Request(f"http://127.0.0.1:{port}/v1/traces", data=body, method="POST",
                                         headers={"Content-Type": "application/x-protobuf"})
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                response.read()
                acked += response.status in (200, 201)
                failed += response.status not in (200, 201)
        except (OSError, urllib.error.HTTPError):
            failed += 1
    results.put((acked, failed, time.time(), time.process_time() - cpu0))


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


RECEIVER_SERVICES = {"payments": "discovery:service:compose.yml:payments"}


def receiver_body() -> bytes:
    """1,000 server spans of one service: one in seven failed, durations 0-299 ms."""
    return proto_request("payments", [(2, 2 if i % 7 == 0 else 0, float(i % 300)) for i in range(SPANS_PER_REQUEST)])


def expected_rows(body: bytes, requests: int, otlp: dict) -> list[dict]:
    """What the receiver must emit after `requests` copies of `body`, from the Python reference window."""
    window = feeds.SpanWindow(otlp)
    spans = feeds.spans_from_protobuf(body)
    for _ in range(min(requests, feeds.MAX_SPANS_PER_SERVICE // len(spans) + 1)):
        window.ingest(spans, 0.0)  # every request is the same, so the window's tail is too
    return [{**row, "observed_at": "T"} for row in window.observations(0.0)]


def receiver_run(command: list[str], workdir: Path, seconds: float, clients: int) -> dict:
    port = free_port()
    otlp = {"port": port, "services": RECEIVER_SERVICES, "window_seconds": 60, "emit_seconds": 1}
    config = {"schema_version": 1, "kind": "ONTOLOGYEX_FEEDS", "output": "obs.jsonl", "otlp": otlp}
    workdir.mkdir(parents=True)
    (workdir / "feeds.json").write_text(json.dumps(config))
    body = receiver_body()
    process = subprocess.Popen([*command, "run", "--config", str(workdir / "feeds.json")],
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    context = multiprocessing.get_context("fork" if sys.platform == "linux" else "spawn")
    try:
        for _ in range(150):
            try:
                socket.create_connection(("127.0.0.1", port), timeout=0.2).close()
                break
            except OSError:
                time.sleep(0.1)
        else:
            raise BenchError(f"{Path(command[-1]).name} did not listen")
        results = context.Queue()
        start_at = time.time() + 0.5
        workers = [context.Process(target=_client, args=(port, body, start_at, start_at + seconds, results))
                   for _ in range(clients)]
        for w in workers:
            w.start()
        time.sleep(max(0.0, start_at - time.time()))
        server_cpu0 = proc_cpu(process.pid)
        done = [results.get(timeout=seconds + 120) for _ in workers]
        server_cpu1 = proc_cpu(process.pid)
        for w in workers:
            w.join()
        elapsed = max(r[2] for r in done) - start_at
        acked, failed = sum(r[0] for r in done), sum(r[1] for r in done)
        peak = proc_peak_kib(process.pid)
        rows, accepted = _settled(workdir, acked * SPANS_PER_REQUEST)
    finally:
        process.terminate()
        process.wait(timeout=10)
    server_cpu = server_cpu1 - server_cpu0 if server_cpu0 is not None and server_cpu1 is not None else None
    spans = acked * SPANS_PER_REQUEST
    return {"spans_per_second": spans / elapsed, "elapsed": elapsed, "acked_requests": acked, "failed_requests": failed,
            "server_cpu": server_cpu, "client_cpu": sum(r[3] for r in done),
            "peak_rss_kib": peak,
            "accepted_spans": accepted, "expected_spans": spans, "rows": rows,
            "expected_rows": expected_rows(body, acked, otlp)}


def _settled(workdir: Path, expected: int, timeout: float = 20.0) -> tuple[list[dict], int | None]:
    """The rows of the first emit after every acknowledged span was counted (or what there was at the timeout)."""
    status_path, out = workdir / "obs.status.json", workdir / "obs.jsonl"
    deadline, accepted, counted_at = time.time() + timeout, None, None
    while time.time() < deadline:
        try:
            status = json.loads(status_path.read_text())
            accepted = int(status["feeds"]["otlp"]["detail"].split()[0])
            generated = status["generated_at"]
        except (OSError, ValueError, KeyError, IndexError):
            time.sleep(0.1)
            continue
        if accepted >= expected and counted_at is None:
            counted_at = generated
        elif counted_at is not None and generated != counted_at:
            break  # an emit that began after the last span was counted
        time.sleep(0.1)
    try:
        rows = [json.loads(line) for line in out.read_text().splitlines() if line.strip()]
    except OSError:
        rows = []
    last = {}
    for row in rows:
        last[row["component_id"]] = {**row, "observed_at": "T"}
    return [last[k] for k in sorted(last)], accepted


def otlp_receiver(binary: Path | None, tmp: Path, runs: int, seconds: float, clients: int) -> dict:
    commands = {"python": [sys.executable, str(SCRIPTS / "feeds.py")], "rust": [str(binary)] if binary else None}
    engines, problems, compared = {}, [], {}
    for name, command in commands.items():
        if command is None:
            engines[name] = not_run("no ontologyex-feeds binary")
            continue
        samples = [receiver_run(command, tmp / f"{name}-{i}", seconds, clients) for i in range(runs)]
        for i, s in enumerate(samples):
            if s["accepted_spans"] != s["expected_spans"]:
                problems.append(f"{name} run {i + 1}: acknowledged {s['expected_spans']:,} spans, "
                                f"counted {s['accepted_spans']}")
            if s["rows"] != s["expected_rows"]:
                problems.append(f"{name} run {i + 1}: emitted {json.dumps(s['rows'])[:300]}, "
                                f"expected {json.dumps(s['expected_rows'])[:300]}")
        compared[name] = samples[-1]["rows"]
        cpu = [s["server_cpu"] for s in samples if s["server_cpu"] is not None]
        engines[name] = {
            "status": "MEASURED", "runs": runs, "warmup_runs": 0, "seconds_per_run": seconds, "clients": clients,
            "spans_per_second": summary([s["spans_per_second"] for s in samples], 0),
            "server_cpu_seconds": summary(cpu, 3) if cpu else None,
            "cores_used": round(statistics.median(c / s["elapsed"] for c, s in zip(cpu, samples)), 2) if cpu else None,
            "spans_per_cpu_second": (round(statistics.median(s["expected_spans"] / s["server_cpu"] for s in samples))
                                     if cpu and all(cpu) else None),
            "client_cores_used": round(statistics.median(s["client_cpu"] / s["elapsed"] for s in samples), 2),
            "peak_rss_mib": (round(max(s["peak_rss_kib"] for s in samples) / 1024, 1)
                             if all(s["peak_rss_kib"] for s in samples) else None),
            "failed_requests": sum(s["failed_requests"] for s in samples)}
    if problems:
        check = correctness("DIFFERENT", "; ".join(problems))
    elif "rust" not in compared:
        check = correctness("NOT_COMPARED", "Rust was not run (Python matched the reference window)")
    else:
        check = correctness("SAME", "every acknowledged span was counted, and the observation each engine emitted "
                                    "after the load equals the Python reference window computed on the same spans")
    return {"workload": "otlp_receiver", "title": "OTLP receiver under load",
            "input": {"spans_per_request": SPANS_PER_REQUEST, "clients": clients, "seconds": seconds},
            "method": "OTLP/HTTP protobuf from Python client processes on the same machine, a fresh receiver "
                      "per run (synthetic spans)",
            "engines": engines, "correctness": check, "comparison": compare(engines, check, "otlp_receiver")}


# ---------------------------------------------------------------- comparison and caveats

def compare(engines: dict, check: dict, workload: str) -> dict:
    """Rust relative to Python, or why there is no comparison."""
    if check["status"] != "SAME":
        return {"withheld": "ANSWERS_DIFFER" if check["status"] == "DIFFERENT" else "NOT_BOTH_RUN"}
    py, rs = engines["python"], engines["rust"]
    if workload == "otlp_receiver":
        return {"throughput": ratio(rs["spans_per_second"]["median"], py["spans_per_second"]["median"]),
                "work_per_cpu_second": ratio(rs["spans_per_cpu_second"], py["spans_per_cpu_second"]),
                "memory": ratio(py["peak_rss_mib"], rs["peak_rss_mib"])}
    return {"wall_time": ratio(py["wall_seconds"]["median"], rs["wall_seconds"]["median"]),
            "cpu_time": ratio(py["cpu_seconds"]["median"], rs["cpu_seconds"]["median"]),
            "memory": ratio(py["peak_rss_mib"], rs["peak_rss_mib"])}


def caveats(report: dict) -> list[dict]:
    found = []
    profiles = {e["profile"] for e in report["conditions"]["engines"].values() if e}
    if "debug" in profiles:
        found.append({"code": "DEBUG_BUILD", "text": "Debug builds were measured: unoptimized Rust, so these "
                                                     "times say nothing about release speed. The answers still count."})
    if "unknown" in profiles:
        found.append({"code": "UNKNOWN_BUILD", "text": "A binary outside engine/target/{release,debug}: its build "
                                                       "profile is not known."})
    machine = report["conditions"]["machine"]
    if machine["load_average_at_start"][0] > 0.5 * machine["usable_cpus"]:
        found.append({"code": "BUSY_MACHINE", "text": f"The 1-minute load average was "
                                                      f"{machine['load_average_at_start'][0]} on "
                                                      f"{machine['usable_cpus']} usable CPUs when it started."})
    for w in report["workloads"]:
        for name, e in w["engines"].items():
            metric = e.get("wall_seconds") or e.get("spans_per_second")
            if e["status"] == "MEASURED" and metric["n"] > 1 and metric["spread_pct"] > NOISY_SPREAD_PCT:
                found.append({"code": "NOISY", "text": f"{w['title']}, {name}: p10 to p90 spans "
                                                       f"{metric['spread_pct']}% of the median."})
        if w["workload"] == "otlp_receiver":
            for name, e in w["engines"].items():
                if e["status"] != "MEASURED" or e["cores_used"] is None:
                    continue
                busy = e["cores_used"] + e["client_cores_used"]
                if busy >= 0.85 * machine["usable_cpus"]:
                    found.append({"code": "MACHINE_SATURATED",
                                  "text": f"{w['title']}, {name}: the receiver ({e['cores_used']} cores) and its "
                                          f"Python clients ({e['client_cores_used']} cores) used {busy:.1f} of "
                                          f"{machine['usable_cpus']} CPUs; the throughput is a lower bound set "
                                          f"partly by the clients."})
            if any(e.get("status") == "MEASURED" and e["cores_used"] is None for e in w["engines"].values()):
                found.append({"code": "NO_PROC", "text": "No /proc here: CPU time of the receiver and peak "
                                                         "memory were not measured."})
    if report["conditions"]["uncommitted_changes"]:
        found.append({"code": "UNCOMMITTED", "text": "The checkout had uncommitted changes when it was measured."})
    return found


# ---------------------------------------------------------------- reports

def _s(seconds: float) -> str:
    return f"{seconds * 1000:.1f} ms" if seconds < 1 else f"{seconds:.2f} s"


def _n(value: float | None) -> str:
    return "–" if value is None else f"{value:,.0f}"


def _x(value: float | None, better: str, worse: str) -> str:
    if value is None:
        return "–"
    return f"{value:.1f}× {better}" if value >= 1 else f"{1 / value:.1f}× {worse}"


def _mib(value: float | None, note: str | None = None) -> str:
    return f"{value} MiB" if value is not None else (note.split(":")[0] if note else "–")


def _row(label: str, cells: dict, engines: dict) -> str:
    return f"| {label} | " + " | ".join(cells(engines[n]) if engines[n]["status"] == "MEASURED" else "not run"
                                         for n in ("python", "rust")) + " |"


def _band(stat: dict, fmt) -> str:
    return f"{fmt(stat['median'])} ({fmt(stat['p10'])}–{fmt(stat['p90'])})" if stat["n"] > 1 else fmt(stat["median"])


def markdown(report: dict) -> str:
    c = report["conditions"]
    m = c["machine"]
    profiles = sorted({e["profile"] for e in c["engines"].values() if e}) or ["no Rust"]
    lines = [
        "# OntologyEX engine benchmark", "",
        f"Measured {c['measured_at']} on {m['cpu']} ({m['usable_cpus']} usable CPUs"
        + (f", cgroup limit {m['cgroup_cpu_limit']}" if m["cgroup_cpu_limit"] else "")
        + (f", {m['memory_gib']} GiB" if m["memory_gib"] else "") + f"), {c['os']}; {c['python']}; "
        f"{c['rustc'] or 'rustc not found'}; {'/'.join(profiles)} build; commit {(c['commit'] or 'unknown')[:12]}"
        + (" with uncommitted changes" if c["uncommitted_changes"] else "") + ".", "",
        "Time, cost and correctness are reported apart. Times are medians with the p10–p90 range "
        "(nearest rank) in brackets. A comparison is given only when both engines gave the same answers.", ""]
    for w in report["workloads"]:
        e, check, comp = w["engines"], w["correctness"], w["comparison"]
        inputs = ", ".join(f"{k.replace('_', ' ')} {v:,}" if isinstance(v, int) else f"{k.replace('_', ' ')} {v}"
                           for k, v in w["input"].items())
        lines += [f"## {w['title']}", "", f"{w['method'][0].upper()}{w['method'][1:]}. Input: {inputs}.", "",
                  "| | Python | Rust |", "|---|---|---|"]
        if w["workload"] == "otlp_receiver":
            lines += [_row("Spans per second", lambda x: _band(x["spans_per_second"], _n), e),
                      _row("Receiver CPU, cores used", lambda x: "–" if x["cores_used"] is None else f"{x['cores_used']}", e),
                      _row("Spans per CPU-second", lambda x: _n(x["spans_per_cpu_second"]), e),
                      _row("Peak memory", lambda x: _mib(x["peak_rss_mib"]), e),
                      _row("Client processes, cores used", lambda x: f"{x['client_cores_used']}", e),
                      _row("Failed requests", lambda x: f"{x['failed_requests']}", e)]
        else:
            lines += [_row("Wall time", lambda x: _band(x["wall_seconds"], _s), e),
                      _row("CPU time", lambda x: _band(x["cpu_seconds"], _s), e),
                      _row("Cores used", lambda x: f"{x['cores_used']}", e),
                      _row("Peak memory", lambda x: _mib(x["peak_rss_mib"], x.get("peak_rss_note")), e)]
        lines += ["", f"**Answers: {check['status']}.** {check['detail'][0].upper()}{check['detail'][1:]}.", ""]
        if "withheld" in comp:
            lines += [f"No comparison: {comp['withheld'].replace('_', ' ').lower()}.", ""]
        elif w["workload"] == "otlp_receiver":
            parts = [_x(comp["throughput"], "the throughput", "less throughput"),
                     _x(comp["work_per_cpu_second"], "the work per CPU-second", "less work per CPU-second"),
                     _x(comp["memory"], "less memory", "more memory")]
            lines += ["Rust: " + ", ".join(p for p in parts if p != "–") + ".", ""]
        else:
            lines += [f"Rust: {_x(comp['wall_time'], 'faster', 'slower')}, "
                      f"{_x(comp['cpu_time'], 'less CPU', 'more CPU')}"
                      + (f", {_x(comp['memory'], 'less memory', 'more memory')}" if comp["memory"] else "") + ".", ""]
    lines += ["## Caveats", ""] + ([f"- **{x['code']}**: {x['text']}" for x in report["caveats"]] or ["- None found."])
    lines += ["", "## Conditions", "", "| | |", "|---|---|"]
    for workload, facts in c["engines"].items():
        lines.append(f"| {BINARIES[workload]} | " + (f"{facts['profile']}, {facts['bytes']:,} bytes, sha256 "
                                                     f"`{facts['sha256'][:16]}`" if facts else "not given") + " |")
    lines += [f"| Engine crate version (engine/Cargo.toml) | {c['engine_version']} |", f"| Load average at start | {m['load_average_at_start']} |",
              f"| Settings | {', '.join(f'{k} {v}' for k, v in c['settings'].items())} |", "",
              "Reproduce: `python tests/bench_rust_engines.py --engine-dir engine/target/release` after "
              "`cargo build --release --locked --manifest-path engine/Cargo.toml --bins`. "
              "Numbers depend on the machine; the answers should not.", ""]
    return "\n".join(lines)


def docs_block(report: dict, style: str, link: str) -> str:
    """The short table the docs quote, generated from a saved report so no number is typed by hand."""
    c, m = report["conditions"], report["conditions"]["machine"]
    w = {x["workload"]: x for x in report["workloads"]}
    rows = ["| Job | Python | Rust | |", "|---|---|---|---|"]
    d = w.get("discovery")
    if d and "withheld" not in d["comparison"]:
        py, rs = d["engines"]["python"], d["engines"]["rust"]
        rows.append(f"| Discovery of a {d['input']['files']:,}-file repository with {d['input']['manifests']} "
                    f"manifests{' (CLI, process start included)' if style == 'full' else ''} | "
                    f"{_s(py['wall_seconds']['median'])} | {_s(rs['wall_seconds']['median'])} | "
                    f"**{_x(d['comparison']['wall_time'], 'faster', 'slower')}**, "
                    f"{_x(d['comparison']['cpu_time'], 'less CPU', 'more CPU')} |")
    r = w.get("otlp_receiver")
    if r and "withheld" not in r["comparison"]:
        py, rs = r["engines"]["python"], r["engines"]["rust"]
        rows.append(f"| OTLP trace ingest, {r['input']['clients']} client processes, {r['input']['spans_per_request']:,} "
                    f"spans per request | {_n(py['spans_per_second']['median'])} spans/s | "
                    f"{_n(rs['spans_per_second']['median'])} spans/s | "
                    f"**{_x(r['comparison']['throughput'], 'more', 'less')}** |")
        if style == "full":
            rows.append(f"| OTLP receiver, spans per CPU-second | {_n(py['spans_per_cpu_second'])} | "
                        f"{_n(rs['spans_per_cpu_second'])} | {_x(r['comparison']['work_per_cpu_second'], 'more', 'less')} |")
        if r["comparison"]["memory"]:
            rows.append(f"| OTLP receiver peak memory under that load | {py['peak_rss_mib']} MiB | "
                        f"{rs['peak_rss_mib']} MiB | {_x(r['comparison']['memory'], 'less', 'more')} |")
    e = w.get("entity_context")
    if e and "withheld" not in e["comparison"]:
        py, rs = e["engines"]["python"], e["engines"]["rust"]
        rows.append(f"| Entity context for all {e['input']['entities']} demo entities, as the control room asks"
                    f"{' (Python in process, Rust a process per answer)' if style == 'full' else ''} | "
                    f"{_s(py['wall_seconds']['median'])} | {_s(rs['wall_seconds']['median'])} | "
                    f"{_x(e['comparison']['wall_time'], 'faster', 'slower')} |")
    same = [x for x in report["workloads"] if x["correctness"]["status"] == "SAME"]
    profiles = "/".join(sorted({x["profile"] for x in c["engines"].values() if x}))
    note = (f"Generated from [{link}]({link}): {profiles} builds on {m['cpu']}, {m['usable_cpus']} usable CPUs, "
            f"{c['measured_at'][:10]}, commit {(c['commit'] or 'unknown')[:7]}. Answers compared on "
            f"{len(same)} of {len(report['workloads'])} workloads: the same. "
            "Your numbers will differ; the answers should not.")
    if any(x["code"] == "MACHINE_SATURATED" for x in report["caveats"]):
        note += " The receiver figures are lower bounds: its Python clients shared the same CPUs."
    return "\n".join([BEGIN, *rows, "", note, END])


def write_docs(report_path: Path, check_only: bool = False) -> list[str]:
    """Put the generated table into the docs, or with check_only, say which docs are out of date."""
    report = json.loads(report_path.read_text("utf-8"))
    stale = []
    for doc, style in DOCS.items():
        text = doc.read_text("utf-8")
        start, end = text.find(BEGIN), text.find(END)
        if start < 0 or end < start:
            stale.append(f"{doc.relative_to(ROOT)}: no benchmark markers")
            continue
        link = os.path.relpath(report_path.with_suffix(".md"), doc.parent).replace(os.sep, "/")
        new = text[:start] + docs_block(report, style, link) + text[end + len(END):]
        if new != text:
            stale.append(f"{doc.relative_to(ROOT)}: does not match {report_path.relative_to(ROOT)}")
            if not check_only:
                doc.write_text(new, "utf-8")
    return stale


# ---------------------------------------------------------------- main

def binaries_from(args) -> dict[str, Path | None]:
    chosen = {}
    for workload, name in BINARIES.items():
        explicit = getattr(args, {"discovery": "discover", "entity_context": "view", "otlp_receiver": "feeds"}[workload])
        path = explicit or (args.engine_dir / name if args.engine_dir else None)
        chosen[workload] = path.resolve() if path and path.is_file() else None
        if explicit and chosen[workload] is None:
            raise BenchError(f"{explicit} is not a file")
    return chosen


def run(binaries: dict[str, Path | None], settings: dict, workloads: tuple[str, ...] = WORKLOADS) -> dict:
    report = {"schema_version": SCHEMA_VERSION, "kind": "ONTOLOGYEX_BENCHMARK",
              "conditions": conditions({w: binaries[w] for w in workloads}, settings), "workloads": []}
    with tempfile.TemporaryDirectory(prefix="ontologyex-bench-") as tmp:
        tmp = Path(tmp)
        if "discovery" in workloads:
            repo = tmp / "repo"
            size = build_repo(repo, settings["repo_modules"])
            report["workloads"].append(discovery(binaries["discovery"], repo, size, settings["runs"], 1))
        if "entity_context" in workloads:
            bundle = demo_bundle(tmp)
            report["workloads"].append(entity_context_workload(binaries["entity_context"], bundle,
                                                               settings["context_runs"], 1))
        if "otlp_receiver" in workloads:
            report["workloads"].append(otlp_receiver(binaries["otlp_receiver"], tmp / "receiver",
                                                     settings["receiver_runs"], settings["seconds"],
                                                     settings["clients"]))
    report["caveats"] = caveats(report)
    report["answers_differ"] = [w["workload"] for w in report["workloads"] if w["correctness"]["status"] == "DIFFERENT"]
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--engine-dir", type=Path, help="where the three Rust binaries are (e.g. engine/target/release)")
    parser.add_argument("--discover", type=Path, help="ontologyex-discover (overrides --engine-dir)")
    parser.add_argument("--view", type=Path, help="ontologyex-view (overrides --engine-dir)")
    parser.add_argument("--feeds", type=Path, help="ontologyex-feeds (overrides --engine-dir)")
    parser.add_argument("--workloads", default=",".join(WORKLOADS), help="comma-separated: " + ", ".join(WORKLOADS))
    parser.add_argument("--quick", action="store_true", help="a smaller, shorter run: a correctness gate, not a measure")
    for key, value in FULL.items():
        parser.add_argument(f"--{key.replace('_', '-')}", type=type(value), default=None)
    parser.add_argument("--json", type=Path, help="write the report here")
    parser.add_argument("--markdown", type=Path, help="write the readable report here (appends to $GITHUB_STEP_SUMMARY)")
    parser.add_argument("--write-docs", type=Path, metavar="REPORT", help="quote a saved report in the docs, then stop")
    parser.add_argument("--check-docs", type=Path, metavar="REPORT", help="exit 1 if the docs do not quote it")
    args = parser.parse_args(argv)
    if args.write_docs or args.check_docs:
        stale = write_docs(args.write_docs or args.check_docs, check_only=bool(args.check_docs))
        for line in stale:
            print(line, file=sys.stderr)
        return 1 if stale and args.check_docs else 0
    workloads = tuple(w.strip() for w in args.workloads.split(",") if w.strip())
    if not workloads or set(workloads) - set(WORKLOADS):
        parser.error(f"--workloads takes {', '.join(WORKLOADS)}")
    settings = dict(QUICK if args.quick else FULL)
    for key in FULL:
        if getattr(args, key) is not None:
            settings[key] = getattr(args, key)
    if not 1 <= settings["seconds"] <= 50 or settings["clients"] < 1 or min(settings["runs"], settings["context_runs"],
                                                                             settings["receiver_runs"]) < 1:
        parser.error("seconds must be 1-50 (inside the receiver's window); runs and clients at least 1")
    settings["quick"] = args.quick
    try:
        report = run(binaries_from(args), settings, workloads)
    except BenchError as exc:
        print(f"benchmark: {exc}", file=sys.stderr)
        return 2
    text = json.dumps(report, indent=2) + "\n"
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(text, "utf-8")
    else:
        print(text, end="")
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        mode = "a" if os.environ.get("GITHUB_STEP_SUMMARY") == str(args.markdown) else "w"
        with args.markdown.open(mode, encoding="utf-8") as handle:
            handle.write(markdown(report))
    for workload in report["answers_differ"]:
        check = next(w for w in report["workloads"] if w["workload"] == workload)["correctness"]
        print(f"benchmark: {workload}: the answers differ: {check['detail']}", file=sys.stderr)
    return 1 if report["answers_differ"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
