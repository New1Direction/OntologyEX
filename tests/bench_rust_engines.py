def percentile(values: list[float], q: float) -> float:
    """Nearest-rank percentile: always one of the measured values."""
    ordered = sorted(values)
    return ordered[max(0, math.ceil(q * len(ordered)) - 1)]


def summary(values: list[float], digits: int = 4) -> dict:
    """Median, p10 and p90 (nearest rank), min, max, and the p10-p90 spread as a share of the median."""
    median = statistics.median(values)
    p10, p90 = percentile(values, 0.10), percentile(values, 0.90)
    return {"median": round(median, digits), "p10": round(p10, digits), "p90": round(p90, digits),
            "min": round(min(values), digits), "max": round(max(values), digits), "n": len(values),
            "spread_pct": round(100.0 * (p90 - p10) / median, 1) if median else 0.0}


def ratio(a: float | None, b: float | None, digits: int = 3) -> float | None:
    return round(a / b, digits) if a and b else None


def children_cpu() -> float:
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def proc_cpu(pid: int) -> float | None:
    """CPU seconds (user + system) a live process has used, from /proc; None where there is no /proc."""
    try:
        fields = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
    except OSError:
        return None
    return (int(fields[11]) + int(fields[12])) / os.sysconf("SC_CLK_TCK")


def proc_peak_kib(pid: int) -> int | None:
    try:
        for line in Path(f"/proc/{pid}/status").read_text().splitlines():
            if line.startswith("VmHWM:"):
                return int(line.split()[1])
    except OSError:
        pass
    return None


def run_once(command: list[str]) -> tuple[dict, bytes]:
    """One process to completion: its wall time and CPU time (from wait4), and its output."""
    with tempfile.TemporaryFile() as out:
        started = time.perf_counter()
        process = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=out, stderr=subprocess.DEVNULL)
        _, status, usage = os.wait4(process.pid, 0)
        wall = time.perf_counter() - started
        process.returncode = os.waitstatus_to_exitcode(status)
        out.seek(0)
        data = out.read()
    if process.returncode != 0:
        raise BenchError(f"{Path(command[0]).name} exited {process.returncode}")
    return {"wall": wall, "cpu": usage.ru_utime + usage.ru_stime}, data


def peak_memory_kib(command: list[str]) -> int | None:
    """Peak resident memory of one untimed run, sampled from /proc every half millisecond.

    Not wait4's ru_maxrss: on Linux that also counts the launching process's memory from
    before exec, so every child of a large Python process looks as large as it is."""
    process = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    peak = None
    while process.poll() is None:
        peak = proc_peak_kib(process.pid) or peak
        time.sleep(0.0005)
    return peak


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------- conditions

def _read(path: str) -> str:
    try:
        return Path(path).read_text()
    except OSError:
        return ""


def _command(*args: str) -> str | None:
    try:
        run = subprocess.run(args, capture_output=True, text=True, timeout=20, cwd=ROOT)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return run.stdout.strip() if run.returncode == 0 else None


def build_profile(binary: Path) -> str:
    parts = binary.resolve().parts
    return "release" if "release" in parts else "debug" if "debug" in parts else "unknown"


def binary_facts(binary: Path | None) -> dict | None:
    if binary is None:
        return None
    data = binary.read_bytes()
    return {"name": binary.name, "sha256": sha256(data), "bytes": len(data), "profile": build_profile(binary)}


def conditions(binaries: dict[str, Path | None], settings: dict) -> dict:
    """What the numbers were measured on. Read from the machine, never typed in."""
    cpu = re.search(r"^model name\s*:\s*(.+)$", _read("/proc/cpuinfo"), re.M)
    memory = re.search(r"^MemTotal:\s*(\d+) kB", _read("/proc/meminfo"), re.M)
    try:
        usable = len(os.sched_getaffinity(0))
    except AttributeError:
        usable = os.cpu_count() or 1
    quota = _read("/sys/fs/cgroup/cpu.max").split()
    limit = round(int(quota[0]) / int(quota[1]), 2) if len(quota) == 2 and quota[0] != "max" else None
    crate = re.search(r'^version\s*=\s*"([^"]+)"', _read(str(ROOT / "engine" / "Cargo.toml")), re.M)
    commit = _command("git", "rev-parse", "HEAD")
    dirty = _command("git", "status", "--porcelain", "--untracked-files=no")
    return {
        "measured_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "machine": {"cpu": cpu.group(1).strip() if cpu else platform.processor() or platform.machine(),
                    "architecture": platform.machine(), "logical_cpus": os.cpu_count(), "usable_cpus": usable,
                    "cgroup_cpu_limit": limit,
                    "memory_gib": round(int(memory.group(1)) / 1024 ** 2, 1) if memory else None,
                    "load_average_at_start": [round(x, 2) for x in os.getloadavg()]},
        "os": platform.platform(),
        "python": f"{platform.python_implementation()} {platform.python_version()}",
        "rustc": _command("rustc", "--version"),
        "engine_version": crate.group(1) if crate else None,
        "engines": {workload: binary_facts(path) for workload, path in binaries.items()},
        "commit": commit, "uncommitted_changes": bool(dirty) if dirty is not None else None,
        "settings": settings,
    }


