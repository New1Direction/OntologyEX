def build_repo(root: Path, modules: int = 165) -> dict:
    """35 services, each a compose file with 40 services, package.json and pyproject.toml, plus
    `modules` Python files; 20 workflows. 125 manifests; 5,900 files at the default size."""
    for i in range(35):
        services = "".join(f"  s{j}:\n    image: app:{j}\n    depends_on: [s{(j + 1) % 40}, s{(j + 7) % 40}]\n"
                           f"    environment: {{A: '1', B: \"two\", C: 3}}\n" for j in range(40))
        (root / f"svc{i}").mkdir(parents=True)
        (root / f"svc{i}" / "compose.yml").write_text("services:\n" + services)
        (root / f"svc{i}" / "package.json").write_text(json.dumps({"name": f"svc{i}", "dependencies": {f"d{k}": "1" for k in range(50)}}))
        (root / f"svc{i}" / "pyproject.toml").write_text(f'[project]\nname = "svc{i}"\ndependencies = ["a", "b"]\n')
        for k in range(modules):
            (root / f"svc{i}" / f"module_{k}.py").write_text("x = 1\n")
    (root / ".github" / "workflows").mkdir(parents=True)
    for w in range(20):
        (root / ".github" / "workflows" / f"w{w}.yml").write_text(f"name: Workflow {w}\non: [push]\njobs: {{}}\n")
    return {"files": sum(len(f) for _, _, f in os.walk(root)), "manifests": 125}


def demo_bundle(tmp: Path) -> dict:
    """The bundle the control room builds for the operating-picture demo (synthetic data)."""
    spec = importlib.util.spec_from_file_location("ontologyex_bench_demo", ROOT / "examples/operating-picture/demo.py")
