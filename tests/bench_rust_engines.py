#!/usr/bin/env python3
"""Benchmark the Rust engines against the Python reference: time, cost and correctness, reported apart.

Three workloads, each run the way OntologyEX runs it:

- discovery: `discover_repo.py --repo` vs `ontologyex-discover --repo` on a generated
  repository near the discovery budgets (CLI to CLI, process start included);
- entity_context: the context of every entity in the demo bundle, the way the control
  room computes it (Python in its own process, Rust as one `ontologyex-view` process per answer);
- otlp_receiver: OTLP/HTTP protobuf ingest through `feeds.py run` vs `ontologyex-feeds run`
  under concurrent client processes.

For each engine it reports time (wall seconds over measured runs after a warm-up: median,
p10, p90 by nearest rank), cost (CPU seconds, the cores that implies, peak resident
memory) and, for each workload, whether the answers were the same. A speed-up is only
computed when they were: a faster different answer is not a speed-up. The report also
records what it was measured on (machine, OS, versions, build profile, binary hashes,
commit, load) and the caveats that follow from it.

    python tests/bench_rust_engines.py --engine-dir engine/target/release \
        --json docs/benchmarks/latest.json --markdown docs/benchmarks/latest.md
    python tests/bench_rust_engines.py --engine-dir engine/target/debug --quick   # CI: the correctness gate
    python tests/bench_rust_engines.py --write-docs docs/benchmarks/latest.json   # quote it in the docs

A missing binary is reported as NOT_RUN. Exit status 1 when any answers differ.
Needs Linux or macOS (CPU and memory come from wait4 and /proc).
"""
